# ============ AI 分析时的卖点/场景自动提取 ============
def build_selling_points_analysis(desc: str) -> dict:
    """从描述中抽取卖点、场景、品类、风格"""
    # 简单关键词规则 + 默认值
    selling_points = []
    scene_keywords = []
    category = "家居用品"
    style = "干净高级"

    keyword_map = {
        "防水": "防水防污",
        "保暖": "加绒保暖",
        "加绒": "加绒保暖",
        "防滑": "防滑耐磨",
        "耐磨": "防滑耐磨",
        "软底": "踩屎感软底",
        "软": "踩屎感软底",
        "厚底": "厚底不累脚",
        "不累脚": "厚底不累脚",
        "易擦": "防水易擦",
        "居家": "居家舒适",
        "浴室": "浴室可用",
        "卧室": "卧室可用",
        "干净": "干净高级",
        "高级": "干净高级",
        "品质": "品质感",
    }

    for k, v in keyword_map.items():
        if k in desc and v not in selling_points:
            selling_points.append(v)

    scene_keywords = ["浴室", "卧室", "居家", "客厅", "玄关"]
    scenes = [s for s in scene_keywords if s in desc]
    if not scenes:
        scenes = ["居家", "卧室"]

    categories = ["鞋", "拖", "家居", "厨房", "美妆", "数码", "服饰", "食品"]
    for c in categories:
        if c in desc:
            category_map = {
                "鞋": "鞋履", "拖": "拖鞋", "家居": "家居用品",
                "厨房": "厨房用品", "美妆": "美妆个护",
                "数码": "数码产品", "服饰": "服饰", "食品": "食品",
            }
            category = category_map.get(c, c)
            break

    return {
        "category": category,
        "selling_points": selling_points[:4] if selling_points else ["品质优良", "工艺精湛", "设计时尚", "实用耐用"],
        "scenes": scenes,
        "style": style,
    }
